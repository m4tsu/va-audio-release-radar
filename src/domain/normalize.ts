/**
 * 声優名の表記揺れ吸収 (設計書 §4)。
 *
 * NFKC 正規化で全角英数・全角記号を半角へ寄せたうえで、空白・中黒・各種記号を除去し、
 * 英字を小文字化する。かな⇄カナの変換はしない (別人の空似を防ぐため、ここでは踏み込まない)。
 * 前置語 ("CV." など) も除去しない。除去すると別人の空似より広く一致してしまうリスクがあるため
 */

// NFKC 適用後に残る/現れる記号をまとめて除去する。
// 空白: \s は半角・全角スペース (U+3000) を含む
// 括弧: 「」【】と半角・全角の丸括弧 (全角は NFKC で半角化されるため両方書く)
// 読点/句点: 、。(NFKC で変換されない CJK 記号) と半角の , .
// 区切り: ・(中黒) と / ／ (全角は NFKC で半角化される)
// ダッシュ類: - (半角ハイフン) ‐ (U+2010) ー (長音記号)
// 疑問符・感嘆符: ? ! (全角 ？！は NFKC で半角化される)
const SYMBOLS_TO_STRIP = /[\s・「」【】()（）,、.。/／\-‐ー?!]/g;

export function normalizeName(name: string): string {
  return name.normalize("NFKC").replace(SYMBOLS_TO_STRIP, "").toLowerCase();
}
