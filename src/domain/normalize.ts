/**
 * 声優名の表記揺れ吸収。
 *
 * NFKC 正規化で全角英数・全角記号を半角へ寄せたうえで、空白・中黒・各種記号を除去し、
 * 人名の異体字を畳み、英字を小文字化する。かな⇄カナの変換はしない (別人の空似を防ぐため、
 * ここでは踏み込まない)。前置語 ("CV." など) も除去しない。除去すると別人の空似より広く
 * 一致してしまうリスクがあるため
 */

// NFKC 適用後に残る/現れる記号をまとめて除去する。
// 空白: \s は半角・全角スペース (U+3000) を含む
// 括弧: 「」【】と半角・全角の丸括弧 (全角は NFKC で半角化されるため両方書く)
// 読点/句点: 、。(NFKC で変換されない CJK 記号) と半角の , .
// 区切り: ・(中黒) と / ／ (全角は NFKC で半角化される)
// ダッシュ類: - (半角ハイフン) ‐ (U+2010) ー (長音記号)
// 疑問符・感嘆符: ? ! (全角 ？！は NFKC で半角化される)
const SYMBOLS_TO_STRIP = /[\s・「」【】()（）,、.。/／\-‐ー?!]/g;

/**
 * 異体字セレクタ。ここだけは表を持たずに機械的に落とせる。
 *
 * VS1–VS16 (U+FE00–U+FE0F) と IVS (U+E0100–U+E01EF) は、**直前の基底文字と同じ文字の**
 * どの字形を表示するかを選ぶだけの符号で、文字そのものを変えない
 * (Unicode 標準 Annex #45 / 23.4 Variation Selectors)。
 * したがって取り除いても別の文字と混ざることはなく、「葛󠄀城」と「葛城」が別扱いになるのを防げる。
 * NFKC はセレクタを落とさないので、ここで明示的に除去する
 */
const VARIATION_SELECTORS = /[︀-️\u{E0100}-\u{E01EF}]/gu;

/**
 * NFKC が畳まない CJK 互換漢字のうち、日本語の人名に現れるもの。
 *
 * 互換漢字 (U+F900–U+FAFF) の大半は統合漢字への正準分解を持つので NFKC が畳む
 * (例: 塚 U+FA10 → 塚 U+585A)。畳まれないのは Unicode 3.2 で JIS X 0213 のために
 * 追加された 12 字 (U+FA0E, FA0F, FA11, FA13, FA14, FA1F, FA21, FA23, FA24, FA27–FA29) で、
 * これらは正準分解を持たない。**その 12 字のうち、統合漢字側の相手が確実に分かるものだけ**を書く。
 * 残り 11 字は相手を確認できていないので入れない
 */
const COMPATIBILITY_IDEOGRAPH_VARIANTS: ReadonlyArray<readonly [string, string]> = [
  // 﨑 (U+FA11) → 崎 (U+5D0E)。いわゆる「たつさき」。JIS X 0213 が人名用の字形として
  // 別に符号化したため互換漢字ブロックに入っているが正準分解が無く NFKC では畳まれない。
  // 実データでも同一人物が両方の字で現れている (ポケドラ 天﨑滉平 / AniList 天崎滉平)
  ["﨑", "崎"],
];

/**
 * 常用漢字表 (平成22年内閣告示第2号) が括弧内に「いわゆる康熙字典体」として併記している字。
 *
 * 常用漢字表はこの括弧内の字を**同じ字の字体の違い**として示している。つまり「別の字ではない」
 * ことが国の告示に書かれているので、同一視は声質や作風からの推測 (設計書の別名義の節で禁じたもの)
 * とは性質が違う。ここに書くのは、告示の 361 組のうち**日本語の人名に現れる**ものに限る。
 * 一般の漢字を無差別に畳むと別人を同一視する危険が増えるだけで、名寄せの役には立たない
 */
const KYUJITAI_VARIANTS: ReadonlyArray<readonly [string, string]> = [
  // 齊 (U+9F4A) → 斉 (U+6589)。常用漢字表「斉(齊)」。斉藤/齊藤
  ["齊", "斉"],
  // 齋 (U+9F4B) → 斎 (U+658E)。常用漢字表「斎(齋)」。斎藤/齋藤。
  // 斉 (U+6589) と 斎 (U+658E) は別の字なので、斉藤と斎藤は畳まれない
  ["齋", "斎"],
  // 德 (U+5FB7) → 徳 (U+5FB3)。常用漢字表「徳(德)」。徳井/德井
  ["德", "徳"],
  // 眞 (U+771E) → 真 (U+771F)。常用漢字表「真(眞)」。真一郎/眞一郎
  ["眞", "真"],
  // 瀨 (U+7028) → 瀬 (U+702C)。常用漢字表「瀬(瀨)」。瀬戸/瀨戸
  ["瀨", "瀬"],
  // 郞 (U+90DE) → 郎 (U+90CE)。常用漢字表「郎(郞)」。太郎/太郞。
  // 朗 (U+6717) は別の字なので、太郎と太朗は畳まれない
  ["郞", "郎"],
  // 澤 (U+6FA4) → 沢 (U+6CA2)。常用漢字表「沢(澤)」。花澤/花沢
  ["澤", "沢"],
  // 濱 (U+6FF1) → 浜 (U+6D5C)。常用漢字表「浜(濱)」。濱野/浜野
  ["濱", "浜"],
  // 邊 (U+908A) → 辺 (U+8FBA)。常用漢字表「辺(邊)」。渡邊/渡辺
  ["邊", "辺"],
  // 國 (U+570B) → 国 (U+56FD)。常用漢字表「国(國)」。國府田/国府田
  ["國", "国"],
  // 廣 (U+5EE3) → 広 (U+5E83)。常用漢字表「広(廣)」。廣瀬/広瀬
  ["廣", "広"],
  // 曾 (U+66FE) → 曽 (U+66FD)。常用漢字表「曽(曾)」。曾我部/曽我部
  ["曾", "曽"],
  // 惠 (U+60E0) → 恵 (U+6075)。常用漢字表「恵(惠)」。惠子/恵子
  ["惠", "恵"],
  // 來 (U+4F86) → 来 (U+6765)。常用漢字表「来(來)」。未來/未来
  ["來", "来"],
  // 淺 (U+6DFA) → 浅 (U+6D45)。常用漢字表「浅(淺)」。淺沼/浅沼
  ["淺", "浅"],
  // 瀧 (U+7027) → 滝 (U+6EDD)。常用漢字表「滝(瀧)」。瀧本/滝本
  ["瀧", "滝"],
  // 龍 (U+9F8D) → 竜 (U+7ADC)。常用漢字表「竜(龍)」。龍之介/竜之介。
  // 対を足したら、別人が同じ鍵にならないかを `npm run db:check-name-variants` で確かめる
  ["龍", "竜"],
];

/**
 * 常用漢字表には無いが、実データで字体の割れが観測された人名の異体字。
 *
 * 根拠は告示ではなく、(1) 字形が新字体と一対一に対応していること、(2) このプロジェクトの
 * 実データで同一人物が両方の字で現れていること、の 2 点。(2) が無いものは §16 の列挙に
 * 限っており、「人名用の異体字らしい」という心証で足したものは 1 つも入れていない
 */
const NAME_VARIANTS_BEYOND_JOYO: ReadonlyArray<readonly [string, string]> = [
  // 髙 (U+9AD9) → 高 (U+9AD8)。通称「はしご高」。実データで同一人物が両方で現れている
  // (DLsite 日髙のり子 / AniList 日高のり子、Audible 髙橋孝治 / AniList 高橋孝治)
  ["髙", "高"],
  // 濵 (U+6FF5) → 浜 (U+6D5C)。濱 (U+6FF1) の旁を変えた字形で、濱 と同じく浜の異体字。
  // 現在のデータには出ていないが §16 が対象として挙げている
  ["濵", "浜"],
  // 邉 (U+9089) → 辺 (U+8FBA)。邊 (U+908A) の異体字。渡邉/渡邊/渡辺 の 3 通りが実データにある
  ["邉", "辺"],
  // 栁 (U+6801) → 柳 (U+67F3)。旁を変えた字形。現在のデータには出ていないが §16 が挙げている
  ["栁", "柳"],
];

/**
 * 畳まない字の例 (テストで固定している):
 * 斉 と 斎、郎 と 朗、島 と 嶋 / 嶌、富 と 冨、崎 と 嵜、館 と 舘。
 * 前の 2 組はそもそも別の字。後の 4 組は異体字ではあるが、日本語では別の姓として
 * 使い分けられており (中島と中嶋、富田と冨田)、畳むと別人を同一視しうる。
 * 実データでは畳んでも一致が 1 件も増えなかったので、危険だけを引き受けることになる
 */
const VARIANT_MAP: ReadonlyMap<string, string> = new Map([
  ...COMPATIBILITY_IDEOGRAPH_VARIANTS,
  ...KYUJITAI_VARIANTS,
  ...NAME_VARIANTS_BEYOND_JOYO,
]);

export function normalizeName(name: string): string {
  const stripped = name
    .normalize("NFKC")
    .replace(VARIATION_SELECTORS, "")
    .replace(SYMBOLS_TO_STRIP, "");

  // コードポイント単位で回す。サロゲートペアの漢字を半分ずつ見ないようにするため
  let folded = "";
  for (const character of stripped) folded += VARIANT_MAP.get(character) ?? character;
  return folded.toLowerCase();
}

/** 畳んでいる異体字の一覧 (異体字 → 寄せ先)。検査スクリプトとテストが読む */
export function nameVariantPairs(): ReadonlyArray<readonly [string, string]> {
  return [...VARIANT_MAP];
}
